/**
 * RawWoodResultViewer — Mode Ingénieur
 *
 * Affiche les résultats du moteur bois massif (raw_wood) avec :
 * - Visualisation SVG directe depuis {x, y, width, height}
 * - Tableau de contrôle par pièce (X, Y, rotation, alertes chevauchement)
 * - Alerte visuelle si une pièce dépasse la planche (dessinée en rouge)
 * - Bouton "Ouvrir le PDF de débit"
 * - Badge "Mode fallback Guillotine" si nécessaire
 */

